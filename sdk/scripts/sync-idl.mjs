// Copy the program's committed IDL into src/idl/ia.ts so the SDK decodes exactly what the program writes.
// Usage: npm run sync-idl   (then npm test)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../program/idl/ia.json");
const file = path.join(here, "..", "src", "idl", "ia.ts");
const idl = JSON.parse(fs.readFileSync(src, "utf8"));
// docs are for humans reading the JSON; the SDK ships the layout only
const strip = (v) => Array.isArray(v) ? v.map(strip) : v && typeof v === "object" ? Object.fromEntries(Object.entries(v).filter(([k]) => k !== "docs").map(([k, x]) => [k, strip(x)])) : v;
const lean = strip(idl);
fs.writeFileSync(file,
  `// Generated by scripts/sync-idl.mjs from program/idl/ia.json. Do not edit by hand.\n` +
  `import type { Idl } from "../borsh.js";\n` +
  `export const IA_IDL: Idl & { events?: { name: string; discriminator: number[] }[] } = ${JSON.stringify(lean)} as any;\n`);
console.log(`ia: synced (address ${idl.address}, version ${idl.metadata?.version}, ${idl.instructions.length} instructions, ${idl.events?.length ?? 0} events)`);
